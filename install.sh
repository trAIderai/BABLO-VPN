#!/bin/bash
# BABLO VPN - Installation Script
# For Ubuntu 22.04+

set -e

echo "=========================================="
echo "   BABLO VPN - Installation"
echo "   AmneziaWG + VLESS Reality + Hysteria2"
echo "=========================================="

# Check if running as root
if [ "$EUID" -ne 0 ]; then
    echo "Please run as root: sudo bash install.sh"
    exit 1
fi

# Get server IP
SERVER_IP=$(curl -s ifconfig.me || hostname -I | awk '{print $1}')

# Prompt for domain
echo ""
read -p "Enter your domain (or press Enter to use IP $SERVER_IP): " DOMAIN
if [ -z "$DOMAIN" ]; then
    DOMAIN=$SERVER_IP
fi

# Prompt for password
echo ""
read -sp "Enter admin password for WireGuard UI: " ADMIN_PASSWORD
echo ""

# Update system
echo "[1/7] Updating system..."
apt update && apt upgrade -y

# Install Docker
echo "[2/7] Installing Docker..."
if ! command -v docker &> /dev/null; then
    curl -fsSL https://get.docker.com | sh
    systemctl enable docker
    systemctl start docker
else
    echo "Docker already installed"
fi

# Install Docker Compose plugin
echo "[3/7] Checking Docker Compose..."
docker compose version || apt install -y docker-compose-plugin

# Install Git
echo "[4/7] Checking Git..."
apt install -y git

# Clone or update repository
echo "[5/7] Downloading project..."
if [ -d "/opt/bablo-vpn" ]; then
    cd /opt/bablo-vpn
    git pull origin main || true
else
    git clone https://github.com/trAIderai/BABLO-VPN.git /opt/bablo-vpn
    cd /opt/bablo-vpn
fi

# Configure environment
echo "[6/7] Configuring environment..."

# Generate unique random AmneziaWG magic headers (H1-H4)
generate_unique_h() {
    local h1 h2 h3 h4
    h1=$((RANDOM * RANDOM % 2000000000 + 1000000))
    h2=$((RANDOM * RANDOM % 2000000000 + 1000000))
    while [ "$h2" -eq "$h1" ]; do
        h2=$((RANDOM * RANDOM % 2000000000 + 1000000))
    done
    h3=$((RANDOM * RANDOM % 2000000000 + 1000000))
    while [ "$h3" -eq "$h1" ] || [ "$h3" -eq "$h2" ]; do
        h3=$((RANDOM * RANDOM % 2000000000 + 1000000))
    done
    h4=$((RANDOM * RANDOM % 2000000000 + 1000000))
    while [ "$h4" -eq "$h1" ] || [ "$h4" -eq "$h2" ] || [ "$h4" -eq "$h3" ]; do
        h4=$((RANDOM * RANDOM % 2000000000 + 1000000))
    done
    echo "$h1 $h2 $h3 $h4"
}

AWG_HEADERS=$(generate_unique_h)
AWG_H1=$(echo "$AWG_HEADERS" | awk '{print $1}')
AWG_H2=$(echo "$AWG_HEADERS" | awk '{print $2}')
AWG_H3=$(echo "$AWG_HEADERS" | awk '{print $3}')
AWG_H4=$(echo "$AWG_HEADERS" | awk '{print $4}')

echo "Generated AmneziaWG magic headers: H1=$AWG_H1 H2=$AWG_H2 H3=$AWG_H3 H4=$AWG_H4"

# Install AmneziaWG kernel module via DKMS (auto-rebuilds on kernel upgrades)
echo "Installing AmneziaWG kernel module (DKMS)..."
DEBIAN_FRONTEND=noninteractive add-apt-repository -y ppa:amnezia/ppa
apt-get update -qq
DEBIAN_FRONTEND=noninteractive apt-get install -y -qq amneziawg-dkms amneziawg-tools
modprobe amneziawg
echo "amneziawg" > /etc/modules-load.d/amneziawg.conf

# apt amneziawg-tools слинкован против glibc Ubuntu и не запустится в Alpine 3.15 контейнере wg-easy
# (контейнер требует musl-совместимые бинарники). Пересобираем awg/awg-quick в Alpine 3.15,
# кладём поверх apt-овых и фиксируем hold, чтобы apt upgrade не вернул свою glibc-версию.
echo "Building musl-compatible awg/awg-quick for wg-easy container..."
mkdir -p /root/awg-build
docker run --rm -v /root/awg-build:/out alpine:3.15 sh -c "\
  apk add --no-cache git make gcc musl-dev linux-headers libmnl-dev libmnl-static bash >/dev/null 2>&1 && \
  cd /tmp && git clone --depth 1 https://github.com/amnezia-vpn/amneziawg-tools.git >/dev/null 2>&1 && \
  cd amneziawg-tools/src && make >/dev/null 2>&1 && make install >/dev/null 2>&1 && \
  cp /usr/bin/awg /out/awg && cp /usr/bin/awg-quick /out/awg-quick && \
  chmod 755 /out/awg /out/awg-quick"
install -m 0755 /root/awg-build/awg /usr/bin/awg
install -m 0755 /root/awg-build/awg-quick /usr/bin/awg-quick
apt-mark hold amneziawg-tools
echo "AmneziaWG kernel module (DKMS) and musl-compatible tools installed."

# Create .env file
cat > /opt/bablo-vpn/.env << EOF
# BABLO VPN Configuration
# Generated by install.sh on $(date)

WG_HOST=$DOMAIN
PASSWORD=$ADMIN_PASSWORD

# AmneziaWG Obfuscation (bypass Russia DPI/TSPU)
AWG_JC=5
AWG_JMIN=50
AWG_JMAX=1000
AWG_S1=75
AWG_S2=75
AWG_H1=$AWG_H1
AWG_H2=$AWG_H2
AWG_H3=$AWG_H3
AWG_H4=$AWG_H4

# Optional: Cloudflare Turnstile (leave empty to disable CAPTCHA)
TURNSTILE_SITE_KEY=
TURNSTILE_SECRET_KEY=

# VLESS Reality Configuration
# These values need to be set after configuring 3x-ui panel
# See .env.example for instructions
VLESS_UUID=
REALITY_PUBLIC_KEY=
REALITY_SHORT_ID=
VLESS_PORT=8443
EOF

chmod 600 /opt/bablo-vpn/.env

# Configure firewall
echo "[7/7] Configuring firewall..."
if command -v ufw &> /dev/null; then
    ufw allow 22/tcp      # SSH
    ufw allow 80/tcp      # HTTP
    ufw allow 443/tcp     # HTTPS
    ufw allow 51820/udp   # WireGuard
    ufw allow 2053/tcp    # 3x-ui Admin Panel
    ufw allow 8443/tcp    # VLESS Reality
    ufw allow 8444/tcp    # Trojan Reality
    ufw allow 8445/udp    # Hysteria2
    echo "y" | ufw enable || true
fi

# Stop old containers
echo "=========================================="
# Конфиг AdGuard не хранится в git: в нём bcrypt-хэш админского пароля,
# а репозиторий публичный. Первый запуск берёт шаблон.
if [ ! -f adguard/AdGuardHome.yaml ]; then
    echo "   Creating adguard/AdGuardHome.yaml from example..."
    cp adguard/AdGuardHome.yaml.example adguard/AdGuardHome.yaml
fi

echo "   Stopping old containers..."
echo "=========================================="
docker stop wg-easy caddy vpn-ui xray-ui adguard-home hysteria2 2>/dev/null || true
docker rm wg-easy caddy vpn-ui xray-ui adguard-home hysteria2 2>/dev/null || true

# Build and start containers
echo "=========================================="
echo "   Building and starting BABLO VPN..."
echo "=========================================="
docker compose build --no-cache
docker compose up -d

# Wait for startup
sleep 10

